const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = '/Users/ozel0t/Notesnook/notesnook';
const task = '/Users/ozel0t/Documents/Codex/2026-10-15/veyran-master-v2-a-mac';
const ts = require(root + '/apps/mobile/node_modules/typescript');
const files = ['packages/editor/src/toolbar/tools/lists.tsx', 'packages/editor/src/toolbar/tools/mac-format.tsx', 'packages/editor/src/toolbar/__tests__/mac-format-menu.test.tsx'];
const source = new Map(files.map(p => [path.join(root,p), fs.readFileSync(path.join(task,'outputs/a12-upper-list-tools/proposal',p),'utf8')]));
const configPath = root + '/packages/editor/tsconfig.json';
const config = ts.readConfigFile(configPath, ts.sys.readFile);
if(config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configPath), {}, configPath);
const options = {...parsed.options, noEmit:true, incremental:false};
const host = ts.createCompilerHost(options);
host.getCurrentDirectory = () => root;
const exists = host.fileExists.bind(host);
host.fileExists = filename => source.has(path.resolve(filename)) || exists(filename);
const read = host.readFile.bind(host);
host.readFile = filename => source.has(path.resolve(filename)) ? source.get(path.resolve(filename)) : read(filename);
const program = ts.createProgram([...parsed.fileNames, ...source.keys()], options, host);
const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
const formatHost = {getCanonicalFileName:p=>p, getCurrentDirectory:()=>root, getNewLine:()=> '\n'};
if(diagnostics.length) process.stdout.write(ts.formatDiagnostics(diagnostics, formatHost));
const receipt = {project:configPath, read_only_root:true, noEmit:true, incremental:false, diagnostic_count:diagnostics.length, overlays:files.map(p=>({path:p,sha256:crypto.createHash('sha256').update(source.get(path.join(root,p))).digest('hex')})), scope:'current Root editor project with exact three-file A12 proposal text overlaid in CompilerHost; no source write'};
fs.writeFileSync(task+'/outputs/a12-upper-list-tools/logs/types-receipt.json',JSON.stringify(receipt,null,2)+'\n');
process.exitCode = diagnostics.length ? 1 : 0;
